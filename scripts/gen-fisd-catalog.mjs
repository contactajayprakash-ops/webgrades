// Generates src/lib/fisdCatalog.js (the Course Plan picker's course list) from
// the FISD course catalog feed:
//   https://resources.friscoisd.org/api/CourseCatalog?lang=en
// which answers { data: { programs, filters } } (an older saved copy may have
// `programs` at the top level). Only high-school courses are kept.
//
// Run: node scripts/gen-fisd-catalog.mjs <catalog.json>
import { readFileSync, writeFileSync } from 'node:fs'

const src = process.argv[2]
if (!src) { console.error('usage: node scripts/gen-fisd-catalog.mjs <catalog.json>'); process.exit(1) }
const j = JSON.parse(readFileSync(src, 'utf8'))
const programs = j.programs || j.data?.programs
if (!Array.isArray(programs) || !programs.length) { console.error('no programs in', src); process.exit(1) }

// HAC's numbered request subject areas, by catalog department.
const DEPT_SUBJECT = {
  'Language Arts': '01', Mathematics: '02', Science: '03', 'Social Studies': '04', Economics: '04',
  'Fine Arts': '05', Speech: '06', Health: '07', 'Technology Applications': '08', 'World Languages': '09',
  'Physical Education/Equivalent': '10', 'Career Technology Education': '11', Elective: '12', 'Local Credit': '12',
}
const clean = (s) => String(s ?? '').replace(/\s+/g, ' ').trim()
const grades = (s) => [...new Set(String(s || '').split(/[,\s]+/).map((g) => {
  const n = Number(g)
  return n > 2000 ? n - 2000 : n // the feed has one "6, 7, 2008"
}).filter((n) => n >= 6 && n <= 12))].sort((a, b) => a - b)

const seen = new Set()
const rows = []
for (const p of programs) {
  const code = clean(p.courseCode).toUpperCase()
  if (!code || seen.has(code)) continue
  const g = grades(p.grade)
  if (!g.some((n) => n >= 9)) continue // middle school only
  seen.add(code)
  const dept = clean(p.department)
  // Every request area the course can file under: HAC lists it where its
  // department, groups or graduation requirement point (AP CS Principles is
  // department CTE but files under Technology Applications; AP Research under
  // General Electives).
  const areas = new Set()
  for (const k of [p.graduationRequirement, dept, p.groups].flatMap((v) => String(v || '').split(/,\s*/))) {
    const a = DEPT_SUBJECT[clean(k)]
    if (a) areas.add(a)
  }
  if (!areas.size) areas.add('12')
  rows.push([
    code,
    clean(p.courseName),
    clean(p.courseDescription), // HAC's short name ("AP Calculus BC YR")
    typeof p.credit === 'number' ? p.credit : (Number(p.credit) || 0),
    g.filter((n) => n >= 9),
    clean(p.courseLevel),
    [...areas].sort(),
    dept,
    clean(p.prerequisites),
  ])
}
rows.sort((a, b) => a[1].localeCompare(b[1]))

const out = `// Auto-generated by scripts/gen-fisd-catalog.mjs from the FISD course catalog
// feed (resources.friscoisd.org/api/CourseCatalog). Do not edit by hand.
// ${rows.length} high-school courses. Row shape:
//   [code, name, hacName, credit, grades, level, subjects, department, prerequisites]
// subjects = HAC's numbered request subject area ("01" Language Arts … "12" General Electives).
export const FISD_CATALOG_FETCHED = ${JSON.stringify(clean(j.fetchedAt || j.cachedAt || ''))}
export const FISD_CATALOG = ${JSON.stringify(rows).replace(/\],\[/g, '],\n[')}
`
writeFileSync(new URL('../src/lib/fisdCatalog.js', import.meta.url), out)
console.log(`wrote src/lib/fisdCatalog.js: ${rows.length} courses`)
